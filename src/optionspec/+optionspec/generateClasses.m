function filePaths = generateClasses(definition, outputFolder, options)
%generateClasses Generate MATLAB option classes from a definition.
%
%   filePaths = optionspec.generateClasses(definition, outputFolder) writes
%   one class for the definition, an optionspec.Definition or the path of
%   a definition file, and one class per group of options, to
%   outputFolder. It returns the paths of the files written.
%
%   An option class holds the values of the options as properties with
%   defaults, help text from "title" and "description", and property
%   validation from the type, "enum", range, number of elements and
%   "x-nonfinite" of each option. A group is a property that holds the
%   class of the group. Composed definitions are generated from their
%   composed schema, so the classes include the included options and do
%   not inherit from each other.
%
%       options = imagestack.options.RigidRegistrationOptions(MaxShift=15);
%       options.Registration.UpsampleFactor = 20;   % checked when set
%       values = options.toStruct();                % for Definition/writeDocument
%
%   The classes depend only on MATLAB. MATLAB converts compatible values
%   when it sets a property, for example 1 to true and "text" to 'text',
%   where optionspec.Definition/validate would reject a value of the wrong
%   class.
%
%   Name-value arguments:
%     Namespace - Namespace of the classes, such as "imagestack.options".
%                 The files are written to the +namespace folders under
%                 outputFolder. Default: "" (no namespace).
%     BaseName  - First part of the class names. Default: the last part of
%                 the definition id in UpperCamelCase, so
%                 "example.rigid-registration" gives RigidRegistration, the
%                 class RigidRegistrationOptions and, for the group Stack,
%                 RigidRegistrationStackOptions.
%
%   Existing files are replaced only if optionspec.generateClasses wrote
%   them; any other file of the same name is an OPTIONSPEC:FileExists error.
%   Commit the generated files, and test with
%   optionspec.checkGeneratedClasses that they match the definition.
%
%   See also optionspec.checkGeneratedClasses, optionspec.Definition

    arguments
        definition {mustBeDefinitionOrFile}
        outputFolder (1,1) string
        options.Namespace (1,1) string {mustBeNamespace} = ""
        options.BaseName (1,1) string = ""
    end

    classFiles = optionspec.internal.planOptionClasses(definition, options.Namespace, options.BaseName);

    filePaths = strings(1, numel(classFiles));
    for i = 1:numel(classFiles)
        filePaths(i) = fullfile(outputFolder, classFiles(i).RelativePath);
        if isfile(filePaths(i)) && ~optionspec.internal.isGeneratedClassFile(filePaths(i))
            error("OPTIONSPEC:FileExists", ...
                "File ""%s"" exists and was not generated by optionspec.generateClasses. " + ...
                "Move it or choose another Namespace or BaseName.", filePaths(i))
        end
    end

    for i = 1:numel(classFiles)
        folder = fileparts(filePaths(i));
        if ~isfolder(folder)
            mkdir(folder)
        end
        [fileId, message] = fopen(filePaths(i), "w", "n", "UTF-8");
        if fileId == -1
            error("OPTIONSPEC:CannotWriteFile", "Cannot write file ""%s"": %s", filePaths(i), message)
        end
        fwrite(fileId, classFiles(i).Text, "char");
        fclose(fileId);
    end
end

function mustBeDefinitionOrFile(value)
    isDefinition = isa(value, "optionspec.Definition") && isscalar(value);
    isFile = (ischar(value) || (isstring(value) && isscalar(value))) && isfile(value);
    if ~(isDefinition || isFile)
        error("OPTIONSPEC:InvalidDefinitionArgument", ...
            "Definition must be an optionspec.Definition or the path of a definition file.")
    end
end

function mustBeNamespace(value)
    if value ~= "" && isempty(regexp(value, '^[A-Za-z]\w*(\.[A-Za-z]\w*)*$', "once"))
        error("OPTIONSPEC:InvalidNamespace", ...
            "Namespace must be names separated by dots, such as ""imagestack.options"".")
    end
end
