function node = emptyNode()
%emptyNode Return a canonical schema node with every keyword absent.
%
%   A node describes one option, a group of options, or the items of an
%   array option. Absent keywords are empty: [] for numbers, Items and
%   Properties, "" for text, {} for Enum and an empty string array for
%   NonFinite. HasDefault tells an absent default apart from a null one.

    node = struct( ...
        "Type", "", ...
        "Nullable", false, ...
        "Title", "", ...
        "Description", "", ...
        "HasDefault", false, ...
        "Default", [], ...
        "Enum", {{}}, ...
        "Minimum", [], ...
        "Maximum", [], ...
        "ExclusiveMinimum", [], ...
        "ExclusiveMaximum", [], ...
        "MinItems", [], ...
        "MaxItems", [], ...
        "Items", [], ...
        "Properties", [], ...
        "Format", "", ...
        "UI", [], ...
        "NonFinite", strings(1, 0));
end
